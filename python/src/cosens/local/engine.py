"""Run RSI in the developer's process, with the developer's model and CoSens only for Memory and Recipe storage."""

import asyncio
import warnings

from ..models import result
from .recipes import LocalRecipeLifecycle
from .store import LocalStore
from .workflow import LocalTaskWorkflow

_UNSET = object()


class LocalRSI(LocalTaskWorkflow, LocalRecipeLifecycle):
    """The workflow methods of ``client.atoms``, backed by local storage and ``model``.

    ``client`` is a ``CoSensClient`` used only for Memory recall (``/v1/memory/*``) and the Recipe store
    (``/v1/recipes``); with ``None`` nothing is recalled or uploaded. ``memory`` is its deprecated name.
    Generation runs inside ``wait_workflow_job``. ``web_search`` is a ``cosens.local.web_search.WebSearch`` the Recipe
    stages may use; the SDK ships no search client, and without one nothing is searched. Queries leave this machine to
    whatever provider it calls, and web text is untrusted data: it cannot add a step without recorded execution evidence.
    """

    def __init__(self, *, client=None, model, state_path=None, memory=_UNSET, web_search=None):
        if memory is not _UNSET:
            if client is not None:
                raise TypeError("pass client, not both client and memory")
            warnings.warn("LocalRSI(memory=...) is deprecated; pass client=...", DeprecationWarning, stacklevel=2)
            client = memory
        self._atoms = client.atoms if client is not None else None
        self._model = model
        self._web_search = web_search
        self._store = LocalStore(state_path)
        self._settling = {}

    async def aclose(self):
        """Stop generations still running in this process, returning them to the queue, and close storage."""
        running = list(self._settling.values())
        for task in running:
            task.cancel()
        if running:
            await asyncio.wait(running)
        self._store.close()

    def _client_atoms(self, method):
        if self._atoms is None:
            raise ValueError(f"{method} requires a client")
        return self._atoms

    async def search_recipes(self, query, *, limit=10):
        """Find Recipes in the service's Recipe store, uploaded from any machine or generated by the service."""
        return await self._client_atoms("search_recipes").search_recipes(query, limit=limit)

    async def list_recipes(self, *, limit=20, cursor=None, origin=None):
        return await self._client_atoms("list_recipes").list_recipes(limit=limit, cursor=cursor, origin=origin)

    async def get_recipe(self, recipe_id, *, version=None):
        """Read a Recipe from the service; pass it to ``create_task(..., recipe=...)`` to continue it here."""
        return await self._client_atoms("get_recipe").get_recipe(recipe_id, version=version)

    async def publish_recipe(self, recipe_id):
        """Retry uploading the current version of a Recipe chain."""
        self._client_atoms("publish_recipe")
        with self._store.reading() as db:
            head = db.execute("SELECT current_candidate_id FROM recipe_heads WHERE recipe_id=?", (recipe_id,)).fetchone()
            if head is None or not head["current_candidate_id"]:
                raise LookupError("usable Recipe not found")
            candidate_id = head["current_candidate_id"]
            state = self._candidate(db, candidate_id)["publish_state"]
        if state != "published":
            state = await self._publish_candidate(candidate_id)
        return result({"recipe_id": recipe_id, "recipe_candidate_id": candidate_id, "publish_state": state})
